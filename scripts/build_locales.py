"""Compile bundled UI catalogs offline; reject broken tokens or incomplete keys."""
import json
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
LOCALES=['enUS','esES','ptBR','frFR','deDE','itIT','ruRU','zhCN','zhTW','koKR']
base=json.loads((ROOT/'locales/enUS.json').read_text(encoding='utf-8'))
protected=re.compile(r'\{\d+\}|FCPLAN/1|FCLOADOUT/1|ForeverContext|WoW Forever|Ctrl\+[CV]|(?<![A-Za-z0-9_])(?:NAME|ACTIVITY|CLASS|BUILD|LEVEL|NODE|NATIVE)(?![A-Za-z0-9_])|/fcontext(?: (?:options|bags|keep|sources|loadouts|plan|compare|talents|gear|session|review|overview|minimap|help|language)(?![A-Za-z0-9_]))?')
def quote(value):
    return json.dumps(value,ensure_ascii=False)
lines=['local _, NS = ...','-- Generated by scripts/build_locales.py; catalogs are bundled, never fetched by the addon.']
for locale in LOCALES:
    values=json.loads((ROOT/'locales'/f'{locale}.json').read_text(encoding='utf-8'))
    assert set(values)==set(base),(locale,'missing/extra keys')
    lines.append(f'NS.LocaleCatalog[{quote(locale)}] = {{')
    for key in sorted(base):
        value=values[key]
        assert isinstance(value,str) and value,(locale,key,'empty value')
        assert not re.search(r'Z{2,}(?:FC|FTOKEN|FNEW)|FCTOKEN\d|FCNEWLINE|FCSEP',value),(locale,key,'translation marker remains')
        assert sorted(protected.findall(key))==sorted(protected.findall(value)),(locale,key,'format/protocol token mismatch')
        lines.append(f'    [{quote(key)}] = {quote(value)},')
    lines.append('}')
patterns=json.loads((ROOT/'locales/patterns.json').read_text(encoding='utf-8'))
for key in sorted(patterns,key=lambda k:-len(re.sub(r'\{\d+\}','',k))):
    assert key in base,key
    lines.append('NS.AddLocalePattern('+quote(key)+')')
(ROOT/'ForeverContext/Locales.lua').write_text('\n'.join(lines)+'\n',encoding='utf-8',newline='\n')
print(f'Compiled {len(base)} keys in {len(LOCALES)} languages; all protocol/format tokens preserved.')
